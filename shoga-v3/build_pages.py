"""Generate ritual.html and ingredients.html from index.html's shared shell.

index.html (the Buy page) owns the header, footer, cart and buy bar. Each file
in src/ holds one page's <main>, with its title and description in the first
two comment lines. Run after editing either:

    python3 build_pages.py
"""
import re
from pathlib import Path

here = Path(__file__).parent
shell = (here / "index.html").read_text()
head, rest = shell.split('  <main id="main">', 1)
tail = rest.split("  </main>", 1)[1]

head = re.sub(r'\s*<link rel="preload" as="image"[^>]*>', "", head)
head = head.replace(' aria-current="page"', "")

for frag in sorted((here / "src").glob("*.html")):
    text = frag.read_text()
    title = re.search(r"<!-- title: (.*?) -->", text).group(1)
    desc = re.search(r"<!-- description: (.*?) -->", text).group(1)
    body = re.sub(r"<!-- (title|description): .*? -->\n", "", text)
    name = frag.stem
    page = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", head)
    page = re.sub(r'(<meta name="description" content=")[^"]*', rf"\g<1>{desc}", page)
    page = page.replace('data-page="buy"', f'data-page="{name}"')
    page = page.replace(f'<a href="{name}.html">', f'<a href="{name}.html" aria-current="page">')
    out = page.replace("<!doctype html>\n", f"<!doctype html>\n<!-- Generated by build_pages.py from src/{frag.name}; edit that file instead. -->\n", 1)
    (here / f"{name}.html").write_text(out + body.rstrip() + "\n" + tail)
    print("wrote", f"{name}.html")
