"""Generate the inner pages (shop, ritual, about) from index.html's shared shell.

index.html owns the shared header, footer, cart and buy bar. Each file in src/
holds one page's <main>, with its title and description in the first two
comment lines. Run after editing either:

    python3 build_pages.py
"""
import re
from pathlib import Path

here = Path(__file__).parent
shell = (here / "index.html").read_text()
m = re.search(r"^[ \t]*<main id=\"main\">.*?</main>\n", shell, re.S | re.M)
before_main, after_main = shell[:m.start()], shell[m.end():]
before_main = re.sub(r'\s*<link rel="preload" as="image"[^>]*>', "", before_main)

for frag_path in sorted((here / "src").glob("*.html")):
    frag = frag_path.read_text()
    title = re.search(r"<!-- title: (.*?) -->", frag).group(1)
    desc = re.search(r"<!-- description: (.*?) -->", frag).group(1)
    body = re.sub(r"<!-- (title|description): .*? -->\n", "", frag)
    name = frag_path.stem

    head = before_main
    head = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", head)
    head = re.sub(r'(<meta name="description" content=")[^"]*', rf"\g<1>{desc}", head)
    head = re.sub(r'(<meta property="og:title" content=")[^"]*', rf"\g<1>{title}", head)
    head = head.replace('data-page="home"', f'data-page="{name}"')
    head = head.replace(f'<a href="{name}.html">', f'<a href="{name}.html" aria-current="page">')

    note = f"<!-- Generated by build_pages.py from src/{frag_path.name}; edit that file instead. -->\n"
    (here / f"{name}.html").write_text(head.replace("<!doctype html>\n", "<!doctype html>\n" + note, 1) + body.rstrip() + "\n" + after_main)
    print("wrote", f"{name}.html")
